// Maps each 2-bit pair (from 8 bits, scanning left-to-right, MSB first) to a
// packed-4bpp byte: '11' -> two colour-15 pixels, '01' -> right pixel only, etc.
static const byte kFontPixels[4] = { 0xFF, 0xF0, 0x0F, 0x00 };
static const byte kFontMask[4]   = { 0xC0, 0x30, 0x0C, 0x03 };

static void buildCharacter(byte c, byte *dst) {
	if (c < 0x20 || c > 0x7E)
		return;
	memset(dst, 0, 32);

	const byte *glyph = kCp437Font + (uint)c * kFontCharHeight;
	for (int row = 0; row < kFontCharHeight; row++) {
		byte bits = glyph[row];
		for (int pair = 0; pair < 4; pair++)
			dst[row * 4 + pair] = kFontPixels[(bits & kFontMask[pair]) >> (6 - pair * 2)];
	}
}

Common::String wrapText(const char *text, int columns) {
	if (!text || columns <= 0)
		return Common::String();

	Common::String out;
	int lineLen = 0;

	while (*text) {
		if (*text == '\n') {
			out += '\n';
			lineLen = 0;
			text++;
			continue;
		}

		const char *wordStart = text;
		while (*text && *text != ' ' && *text != '\n')
			text++;
		int wordLen = (int)(text - wordStart);

		// Start a new line if this word wouldn't fit (including the
		// leading space we'd need to add).
		if (lineLen > 0 && lineLen + 1 + wordLen > columns) {
			out += '\n';
			lineLen = 0;
		}

		if (lineLen > 0) {
			out += ' ';
			lineLen++;
		}
		out += Common::String(wordStart, wordLen);
		lineLen += wordLen;

		if (*text == ' ') text++;
	}

	return out;
}

void drawString(const char *string, int widthPx, int heightPx,
                int leftPx, int topPx, byte *dst) {
	(void)heightPx; // caller guarantees buffer extent; no clipping here.

	byte character[32]; // 8 rows × 4 packed bytes.

	// IMH sprite buffers are packed 4bpp with (widthPx / 2) bytes per row.
	int rowStride = widthPx / 2;
	int textOriginPackedX = leftPx / 2;
	int line = 1;

	// dst points at the packed pixel region inside the caller's buffer; this
	// contract matches the Reuromancer build_string signature which operated
	// on the pixel pointer, not the ImhHeader-preceded buffer.
	byte *origin = dst + rowStride * topPx + textOriginPackedX;
	byte *cursor = origin;

	char c;
	while ((c = *string++) != 0) {
		if (c == '\n') {
			cursor = origin + rowStride * kFontCharHeight * line++;
			continue;
		}
		if ((byte)c < 0x20 || (byte)c > 0x7E)
			continue;

		buildCharacter((byte)c, character);
		for (int row = 0; row < kFontCharHeight; row++) {
			// Each glyph row is 4 packed bytes = 8 pixels = 1 character width.
			memcpy(cursor + row * rowStride, character + row * 4, 4);
		}
		cursor += 4;
	}
}

